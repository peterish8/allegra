#!/usr/bin/env python3
"""
Writes android/app/src/main/java/com/lyricflow/app/views/IconGlyphs.kt: the outlines of the few @expo/vector-icons
glyphs that Kotlin views draw, so a native view shows the same shapes as the React Native <Ionicons>/<MaterialCommunityIcons>.

Each outline is an SVG path on the font's own grid (512 units to the em), moved so the icon's centre is (0, 0) and y points
down: a view scales it by `size / 512` and translates it to the icon's centre, which is where React Native centres the
glyph's text box. Both fonts design their em square centred at y = 192 (ascent 448, descent -64: MaterialCommunityIcons'
hhea, Ionicons' typo metrics, which its USE_TYPO_METRICS bit makes Android use). React Native's font-padded text box is
the head table's bounding box, whose centre is 191 (Ionicons) and 193.5 (MaterialCommunityIcons): under 0.1 dp off at
the sizes drawn, so 192 is used for both.

Needs `pip install fonttools` and `npm ci` in apps/mobile. Run from apps/mobile:  python3 scripts/extract-icon-glyphs.py
Add a glyph by adding its (font, name) below and rerunning; commit the generated file.
"""
import json
import os

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

VENDOR = 'node_modules/@expo/vector-icons/build/vendor/react-native-vector-icons'
OUT = 'android/app/src/main/java/com/lyricflow/app/views/IconGlyphs.kt'
CENTRE_Y = 192  # the em square's middle in font units (ascent 448, descent -64)

GLYPHS = [
    ('Ionicons', 'list'),
    ('Ionicons', 'ellipsis-vertical'),
    ('Ionicons', 'heart'),
    ('Ionicons', 'heart-outline'),
    ('Ionicons', 'search'),
    ('Ionicons', 'albums-outline'),
    ('Ionicons', 'settings-outline'),
    ('Ionicons', 'chevron-forward'),
    ('Ionicons', 'refresh'),
    ('Ionicons', 'volume-medium'),
    ('MaterialCommunityIcons', 'speaker'),
    ('MaterialCommunityIcons', 'devices'),
    ('MaterialCommunityIcons', 'timer-outline'),
    ('MaterialCommunityIcons', 'comment-quote-outline'),
    ('MaterialCommunityIcons', 'fullscreen'),
    ('MaterialCommunityIcons', 'fullscreen-exit'),
    ('MaterialCommunityIcons', 'account-multiple'),
    ('MaterialCommunityIcons', 'laptop'),
    ('MaterialCommunityIcons', 'cellphone'),
]


def const_name(font: str, name: str) -> str:
    prefix = {'Ionicons': 'ION', 'MaterialCommunityIcons': 'MCI'}[font]
    return f"{prefix}_{name.upper().replace('-', '_')}"


def main() -> None:
    fonts = {}
    lines = []
    for font, name in GLYPHS:
        if font not in fonts:
            ttf = TTFont(f'{VENDOR}/Fonts/{font}.ttf')
            glyphmap = json.load(open(f'{VENDOR}/glyphmaps/{font}.json'))
            assert ttf['head'].unitsPerEm == 512, font
            fonts[font] = (ttf, glyphmap)
        ttf, glyphmap = fonts[font]
        glyph_name = ttf.getBestCmap()[glyphmap[name]]
        advance = ttf['hmtx'][glyph_name][0]
        pen = SVGPathPen(ttf.getGlyphSet(), ntos=lambda v: ('%.2f' % v).rstrip('0').rstrip('.'))
        # Font units (y up) to a grid centred on the icon with y down.
        ttf.getGlyphSet()[glyph_name].draw(TransformPen(pen, (1, 0, 0, -1, -advance / 2, CENTRE_Y)))
        lines.append(f'    /** {font} "{name}". */\n    const val {const_name(font, name)} = "{pen.getCommands()}"')

    body = '\n\n'.join(lines)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(f'''package com.lyricflow.app.views

/**
 * Outlines of the vector-icon glyphs Kotlin views draw (generated by scripts/extract-icon-glyphs.py; do not edit).
 * Each is an SVG path on a 512-unit grid centred on (0, 0) with y down: scale it by `size / 512` and translate it to the
 * icon's centre, as React Native centres the glyph's text box.
 */
object IconGlyphs {{
    const val GRID = 512

{body}
}}
''')
    print('wrote', OUT, len(GLYPHS), 'glyphs')


if __name__ == '__main__':
    main()
